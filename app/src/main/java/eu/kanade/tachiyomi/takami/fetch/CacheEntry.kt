package eu.kanade.tachiyomi.takami.fetch

import kotlinx.serialization.Serializable

/**
 * Запись кэша: метаданные страницы без самого тела.
 *
  * Тело лежит отдельным файлом рядом: так индекс остаётся
  * маленьким, а чтение
   * страницы не тянет за собой весь кэш. Поле [ttlMs] хранит
   * срок жизни
  * вместе с
  * разбросом конкретного источника, иначе после перезапуска
  * разброс считался бы
 * заново и часть записей «омолодилась» бы.
 */
@Serializable
data class CacheEntry(
    /** Адрес страницы, по которому её запрашивали. */
    val url: String = "",
    /**
     * Referer на момент запроса: часть сайтов отдаёт от него разную
     * разметку.
     */
    val referer: String = "",
    /**
     * Метка версии от сайта: с ней возможен ответ «не
     * изменилось». */
    val etag: String? = null,
    /**
     * Дата изменения от сайта: второй способ попросить «не
     * изменилось».
     */
    val lastModified: String? = null,
    /** Когда страницу получили в последний раз. */
    val fetchedAt: Long = 0L,
    /** Срок жизни с учётом разброса источника. */
    val ttlMs: Long = 0L,
    /**
     * Отпечаток начала страницы: признак изменения для сайтов без
     * ETag.
     */
    val bodyHash: String = "",
    /** Полный размер тела: ловит правки в хвосте страницы. */
    val sizeBytes: Long = 0L,
    /** Кодировка, в которой страница была прочитана. */
    val charset: String = "UTF-8",
    /** Имя файла с телом. */
    val fileName: String = "",
    /**
     * Когда запись использовали в последний раз: по этому времени
     * идёт вытеснение.
     */
    val lastUsedAt: Long = 0L,
)
