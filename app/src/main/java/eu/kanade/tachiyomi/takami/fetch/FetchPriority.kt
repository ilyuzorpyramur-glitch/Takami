package eu.kanade.tachiyomi.takami.fetch

/** Очередь запроса: человек ждёт ответа или это фоновая работа. */
enum class FetchPriority {
    /**
     * Экран открыт, человек смотрит на список: такие запросы идут
     * первыми.
     */
    INTERACTIVE,

    /**
     * Обновление библиотеки и прочая работа без человека у экрана.
     */
    BACKGROUND,
}
