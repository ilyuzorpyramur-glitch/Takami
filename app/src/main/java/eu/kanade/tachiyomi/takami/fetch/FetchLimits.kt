package eu.kanade.tachiyomi.takami.fetch

/**
 * Лимиты вежливости к сайтам.
 *
  * Значения согласованы и меняются только вместе с приёмкой: от
  * них зависит,
 * не начнёт ли сайт отвечать отказами на наши запросы.
 */
object FetchLimits {
    /** Параллельных запросов на всё приложение. */
    const val MAX_CONCURRENT_TOTAL = 2

    /**
     * Параллельных запросов на один домен: строго последовательно.
     */
    const val MAX_CONCURRENT_PER_HOST = 1

    /** Минимальный интервал между запросами к одному домену. */
    const val MIN_INTERVAL_MS = 1_500L

    /** Средний темп: один запрос в пять секунд, то есть 0.2 rps. */
    const val AVERAGE_INTERVAL_MS = 5_000L

    /**
     * Всплеск: два запроса подряд, дальше пауза до восстановления
     * темпа.
     */
    const val BURST = 2

    /** Дневной потолок запросов к домену на одно устройство. */
    const val DAILY_PER_HOST = 300

    /**
     * Сколько всего попыток делаем для одного запроса (только 429 и
     * 5xx).
     */
    const val RETRY_ATTEMPTS = 3

    /** Паузы между повторами: 5, 30 и 120 секунд. */
    val retryDelaysMs = longArrayOf(5_000L, 30_000L, 120_000L)

    /** Сколько ошибок подряд открывают предохранитель. */
    const val BREAKER_FAILURES = 3

    /** Пауза предохранителя: 15 минут. */
    const val BREAKER_PAUSE_MS = 15L * 60L * 1_000L

    /** Бюджет запросов на одну операцию разбора или ремонта. */
    const val OPERATION_BUDGET = 3

    /** Сколько ждём, если сервер ответил 429 без заголовка Retry-After. */
    const val DEFAULT_RETRY_AFTER_MS = 5_000L

    /**
     * Верхняя граница ожидания по Retry-After: защита от бесконечной
     * паузы.
     */
    const val MAX_RETRY_AFTER_MS = 60L * 60L * 1_000L

    /** Сколько живёт запись о домене без обращений: час. */
    const val HOST_TTL_MS = 60L * 60L * 1_000L

    /**
     * Потолок числа доменов в памяти: сверх него вычищаем самые
     * давние.
     */
    const val MAX_HOSTS = 64
}
